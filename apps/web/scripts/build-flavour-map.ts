// Writes components/flavour/generated/: the UI SDK previews of every demo and gallery example.
//
// One module per primitive folder and kind (`components-dialog.ts`, `demos-dialog.ts`) imports that
// folder's flavour examples statically, and `index.ts` maps each folder to a lazy import of its module.
// A page that shows a UI SDK preview therefore loads one chunk holding the examples it renders (a gallery
// page renders its whole folder; a primitive page its demos) plus the UI SDK primitives, and a Base UI
// reader loads none of it. The examples come from the generated flavour tree (lib/ui-sdk-examples.ts).
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { GENERATED_TREE, REGISTRY_DIR, type ExampleKind, uiSdkAvailable } from "../lib/ui-sdk-examples.ts";

const OUTPUT = path.join(process.cwd(), "components/flavour/generated");
const GENERATOR = path.join(process.cwd(), "../../scripts/ui-sdk-flavour.mjs");
const TREE = path.join(REGISTRY_DIR, GENERATED_TREE);
const KINDS: ExampleKind[] = ["demos", "components"];

// The tree is the registry side's output. Refresh it when its generator knows the command, so `dev` and
// `typecheck` (which do not run build:registry) never read a stale tree.
if (existsSync(GENERATOR) && (await readFile(GENERATOR, "utf8")).includes('"examples"')) {
  const run = spawnSync(process.execPath, [GENERATOR, "examples"], { cwd: path.dirname(GENERATOR), stdio: "inherit" });
  if (run.status !== 0) throw new Error(`build-flavour-map: node scripts/ui-sdk-flavour.mjs examples exited ${run.status}`);
}
if (!existsSync(TREE)) {
  throw new Error(
    `build-flavour-map: no generated flavour tree at ${TREE}. It is written by \`node scripts/ui-sdk-flavour.mjs examples\` (also run by build:registry).`,
  );
}

type RegistryItem = { files: { path: string }[] };

const folders = new Map<string, { key: string; file: string }[]>();
let total = 0;
let skipped = 0;
for (const kind of KINDS) {
  const registry = JSON.parse(await readFile(path.join(REGISTRY_DIR, kind, "registry.json"), "utf8")) as {
    items: RegistryItem[];
  };
  for (const file of registry.items.flatMap((item) => item.files.map((entry) => entry.path))) {
    if (!file.endsWith(".tsx")) continue;
    if (!uiSdkAvailable(kind, file)) {
      skipped++;
      continue;
    }
    if (!existsSync(path.join(TREE, kind, file))) {
      throw new Error(`build-flavour-map: ${GENERATED_TREE}/${kind}/${file} is missing; regenerate the flavour tree.`);
    }
    const [folder, name] = file.slice(0, -".tsx".length).split("/");
    const moduleName = `${kind}-${folder}`;
    const list = folders.get(moduleName) ?? [];
    list.push({ key: name, file: `${kind}/${file.slice(0, -".tsx".length)}` });
    folders.set(moduleName, list);
    total++;
  }
}

// Every example has a UI SDK version (EXCLUDED_EXAMPLES in scripts/ui-sdk-flavour.mjs is empty). One that
// is skipped here would quietly show "no UI SDK version yet" on the site, so it fails instead.
if (skipped > 0) {
  throw new Error(
    `build-flavour-map: ${skipped} example(s) have no UI SDK version (the compat manifest says "variant" but no overlay exists); write the variants or record them in EXCLUDED_EXAMPLES`,
  );
}
if (total === 0) throw new Error("build-flavour-map: no examples found in demos/ or components/");

const HEADER = "// Generated by scripts/build-flavour-map.ts from the UI SDK flavour example tree. Do not edit.\n";
const expected = new Map<string, string>();
for (const [moduleName, entries] of [...folders.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  entries.sort((a, b) => a.key.localeCompare(b.key));
  const imports = entries.map((entry, i) => `import E${i} from "@/${GENERATED_TREE}/${entry.file}";`);
  const map = entries.map((entry, i) => `  ${JSON.stringify(entry.key)}: E${i},`);
  expected.set(
    `${moduleName}.ts`,
    `${HEADER}"use client";\n\nimport type { ComponentType } from "react";\n${imports.join("\n")}\n\nconst previews: Record<string, ComponentType> = {\n${map.join("\n")}\n};\n\nexport default previews;\n`,
  );
}
const index = [...folders.keys()]
  .sort()
  .map((moduleName) => `  ${JSON.stringify(moduleName.replace("-", "/"))}: () => import("./${moduleName}"),`);
expected.set(
  "index.ts",
  `${HEADER}"use client";\n\nimport type { ComponentType } from "react";\n\nexport type PreviewFolder = { default: Record<string, ComponentType> };\n\n/** \`<kind>/<primitive>\` → its UI SDK previews, loaded on demand. */\nexport const uiSdkPreviewFolders: Record<string, () => Promise<PreviewFolder>> = {\n${index.join("\n")}\n};\n`,
);

await mkdir(OUTPUT, { recursive: true });
for (const stale of (await readdir(OUTPUT)).filter((name) => !expected.has(name))) await rm(path.join(OUTPUT, stale));
for (const [name, source] of expected) {
  let current = "";
  try {
    current = await readFile(path.join(OUTPUT, name), "utf8");
  } catch {}
  if (current !== source) await writeFile(path.join(OUTPUT, name), source);
}
console.log(`build-flavour-map: ${total} UI SDK previews in ${folders.size} folders, ${skipped} without a UI SDK version`);
